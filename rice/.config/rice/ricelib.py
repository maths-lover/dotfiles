#!/usr/bin/env python3
"""ricelib.py - the Python half of the rice. Stdlib only. Called by rice.sh:

  ricelib.py palette <ghostty-theme-file> <state-dir>
      Parse a Ghostty theme and write palette.{sh,json,css} into <state-dir>.
  ricelib.py render <template> <out> <state-dir>
      Replace every {{NAME}} in <template> with the palette value NAME.
  ricelib.py accent <state-dir>
      Print "<index> <r> <g> <b>": nearest Apple accent preset + highlight RGB.
  ricelib.py snapshot-take <file>   /  snapshot-restore <file>
      Save / restore every macOS setting the rice touches (see SNAPSHOT_KEYS).
  ricelib.py wallpaper-store <state-dir> <fill-hex>   (plan on stdin)
      Write a wallpaper into macOS's store for EVERY Space listed on stdin, one line
      per Space: "<space idx> <display idx> <flavour> <space uuid> <display uuid> <png>".
  ricelib.py wallpaper-store-restore
      Swap every rice wallpaper in the store back for the user's previous choice.
"""
import copy, datetime, json, os, plistlib, re, shutil, subprocess, sys, time

# ----------------------------------------------------------------------------- colour maths
def hex2rgb(h):
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))

def rgb2hex(rgb):
    return "#%02x%02x%02x" % tuple(max(0, min(255, round(c))) for c in rgb)

def mix(a, b, t):
    """Linear blend of two hex colours; t=0 -> a, t=1 -> b."""
    ra, rb = hex2rgb(a), hex2rgb(b)
    return rgb2hex(tuple(ra[i] + (rb[i] - ra[i]) * t for i in range(3)))

def luminance(h):
    r, g, b = (c / 255 for c in hex2rgb(h))
    return 0.2126 * r + 0.7152 * g + 0.0722 * b

def saturation(h):
    r, g, b = (c / 255 for c in hex2rgb(h))
    mx, mn = max(r, g, b), min(r, g, b)
    return 0 if mx == 0 else (mx - mn) / mx

# ----------------------------------------------------------------------------- palette
def parse_theme(path):
    """Ghostty theme -> dict. Lines look like `palette = 4=#58a6ff`, `background = #0d1117`."""
    pal, keys = {}, {}
    for line in open(path, encoding="utf-8"):
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        k, v = (s.strip() for s in line.split("=", 1))
        if k == "palette":
            idx, col = v.split("=", 1)
            pal[int(idx)] = "#" + col.strip().lstrip("#")
        else:
            keys[k] = "#" + v.lstrip("#") if re.fullmatch(r"#?[0-9a-fA-F]{6}", v) else v
    if len(pal) != 16 or "background" not in keys or "foreground" not in keys:
        sys.exit(f"ricelib: {path} is not a complete Ghostty theme (need 16 palette colours, background, foreground)")
    return pal, keys

def build_palette(theme_name, path):
    pal, keys = parse_theme(path)
    bg, fg = keys["background"].lower(), keys["foreground"].lower()
    is_light = luminance(bg) > 0.5
    # Accent: the cursor colour if it is actually colourful (GitHub blue, CRT green),
    # otherwise ANSI blue (4). Low-saturation cursors (white/grey) are skipped.
    cursor = keys.get("cursor-color", "").lower()
    accent = cursor if cursor and saturation(cursor) > 0.35 else pal[4]
    # Derived shades, all blends between bg and fg so they fit any theme.
    p = {
        "THEME": theme_name,
        "IS_LIGHT": "1" if is_light else "0",
        "APPEARANCE": "light" if is_light else "dark",
        "BG": bg, "FG": fg, "ACCENT": accent, "CURSOR": cursor or accent,
        "BG_ALT": mix(bg, fg, 0.06),      # panels, bar background
        "BG_ALT2": mix(bg, fg, 0.12),     # hovered / raised surfaces
        "BORDER": mix(bg, fg, 0.22),      # inactive borders, separators
        "FG_DIM": mix(fg, bg, 0.40),      # secondary text
        "FG_MUTED": mix(fg, bg, 0.60),    # placeholders, disabled text
        "SEL_BG": keys.get("selection-background", mix(bg, accent, 0.35)).lower(),
    }
    for i in range(16):
        p[f"C{i}"] = pal[i].lower()
    # Convenience variants: without '#', and 0xAARRGGBB as sketchybar/borders want.
    for k in list(p):
        v = p[k]
        if isinstance(v, str) and re.fullmatch(r"#[0-9a-f]{6}", v):
            p[k + "_HEX"] = v[1:]
            p[k + "_0X"] = "0xff" + v[1:]
            p[k + "_RGB"] = ",".join(str(c) for c in hex2rgb(v))
    return p

def write_palette(p, state):
    os.makedirs(state, exist_ok=True)
    with open(os.path.join(state, "palette.sh"), "w") as f:
        f.write("# generated by ricelib.py - source me\n")
        for k, v in p.items():
            f.write(f'RICE_{k}="{v}"\n')
    with open(os.path.join(state, "palette.json"), "w") as f:
        json.dump(p, f, indent=2)
    with open(os.path.join(state, "palette.css"), "w") as f:
        f.write(":root {\n" + "".join(f"  --rice-{k.lower().replace('_', '-')}: {v};\n"
                                      for k, v in p.items() if not k.endswith(("_0X", "_HEX", "_RGB"))) + "}\n")

def load_palette(state):
    return json.load(open(os.path.join(state, "palette.json")))

def render(template, out, state):
    p = load_palette(state)
    src = open(template, encoding="utf-8").read()
    missing = set()
    def sub(m):
        k = m.group(1)
        if k not in p:
            missing.add(k); return m.group(0)
        return str(p[k])
    text = re.sub(r"\{\{([A-Z0-9_]+)\}\}", sub, src)
    if missing:
        sys.exit(f"ricelib: template {template} uses unknown keys: {sorted(missing)}")
    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    with open(out, "w", encoding="utf-8") as f:
        f.write(text)

# ----------------------------------------------------------------------------- accent
# Apple only allows these presets for AppleAccentColor; we snap to the nearest.
APPLE_ACCENTS = {-1: "#8c8c8c", 0: "#ff5257", 1: "#f7821b", 2: "#ffc600",
                 3: "#62ba46", 4: "#007aff", 5: "#a550a7", 6: "#f74f9e"}

def accent(state):
    a = hex2rgb(load_palette(state)["ACCENT"])
    best = min(APPLE_ACCENTS, key=lambda i: sum((x - y) ** 2 for x, y in zip(a, hex2rgb(APPLE_ACCENTS[i]))))
    r, g, b = (round(c / 255, 6) for c in a)
    print(best, r, g, b)

# ----------------------------------------------------------------------------- snapshot
def sh(cmd):
    r = subprocess.run(cmd, shell=True, capture_output=True, text=True)
    return r.stdout.strip() if r.returncode == 0 else None

# (domain, key) -> how to read/write. Value None in the snapshot = key was absent.
SNAPSHOT_KEYS = [
    ("com.apple.dock", "autohide"), ("com.apple.dock", "autohide-delay"),
    ("com.apple.dock", "autohide-time-modifier"), ("com.apple.dock", "show-recents"),
    ("com.apple.dock", "mru-spaces"),
    ("-g", "AppleAccentColor"), ("-g", "AppleHighlightColor"),
    ("com.google.Chrome", "BrowserThemeColor"),
]

def snapshot_take(path):
    snap = {"defaults": {}}
    for dom, key in SNAPSHOT_KEYS:
        snap["defaults"][f"{dom} {key}"] = sh(f"defaults read {dom} {key}")
    snap["dark_mode"] = sh("osascript -e 'tell application \"System Events\" to tell appearance preferences to get dark mode'")
    snap["menubar_autohide"] = sh("osascript -e 'tell application \"System Events\" to tell dock preferences to get autohide menu bar'")
    snap["wallpaper"] = sh("wallpaper get --screen all") or ""
    vc = os.path.expanduser("~/Library/Application Support/Vencord/settings/settings.json")
    snap["vencord_enabled_themes"] = json.load(open(vc)).get("enabledThemes", []) if os.path.exists(vc) else None
    os.makedirs(os.path.dirname(path), exist_ok=True)
    json.dump(snap, open(path, "w"), indent=2)
    print(f"snapshot written to {path}")

def snapshot_restore(path):
    snap = json.load(open(path))
    for dk, val in snap["defaults"].items():
        dom, key = dk.split(" ", 1)
        if val is None:
            subprocess.run(f"defaults delete {dom} {key}", shell=True, capture_output=True)
        else:
            # defaults read prints ints/floats/strings bare; -string round-trips all of them
            # except booleans-as-int for the dock, which also accept plain ints.
            subprocess.run(["defaults", "write", *dom.split(), key, val], capture_output=True)
    if snap.get("dark_mode") in ("true", "false"):
        sh(f"osascript -e 'tell application \"System Events\" to tell appearance preferences to set dark mode to {snap['dark_mode']}'")
    if snap.get("menubar_autohide") in ("true", "false"):
        sh(f"osascript -e 'tell application \"System Events\" to tell dock preferences to set autohide menu bar to {snap['menubar_autohide']}'")
    # Wallpapers: heal the per-Space store first (keeps aerials / dynamic wallpapers
    # intact); only if some entry could not be healed fall back to the flat image
    # paths `wallpaper get` reported before install (screens are numbered from 0).
    try:
        left = wallpaper_store_restore()
    except Exception as e:          # noqa: BLE001 - never let this abort the restore
        print(f"wallpaper store: could not heal ({e})"); left = 1
    if left:
        for i, line in enumerate(snap.get("wallpaper", "").splitlines()):
            if line and os.path.exists(line):
                sh(f"wallpaper set '{line}' --screen {i}")
    vc = os.path.expanduser("~/Library/Application Support/Vencord/settings/settings.json")
    if snap.get("vencord_enabled_themes") is not None and os.path.exists(vc):
        s = json.load(open(vc)); s["enabledThemes"] = snap["vencord_enabled_themes"]
        json.dump(s, open(vc, "w"), indent=4)
    sh("killall Dock")
    print("snapshot restored")

# ----------------------------------------------------------------------------- wallpaper store
# macOS (Sonoma and later) keeps the wallpaper of every Space on every display in one
# binary plist. NSWorkspace, AppleScript and the `wallpaper` CLI only ever change the
# Space that is on screen right now, so to give every Space its own picture without
# visiting each one we edit that store directly, then SIGKILL WallpaperAgent so the
# relaunched one re-reads the file (see _commit). Verified on macOS 27.2.
#
# Layout (only the parts we touch):
#   Spaces[<space uuid>].Default                    what the Space shows on any display
#   Spaces[<space uuid>].Displays[<display uuid>]   ... on that particular display
#   Displays[<display uuid>]                        default for NEW Spaces on that display
#   SystemDefault                                   default for everything else
# Every entry is {Type: individual, Desktop: {...}, Idle: {...}}: Desktop is the
# wallpaper, Idle the screen saver. We only ever replace Desktop. Space and display
# UUIDs are the ones `yabai -m query --spaces/--displays` report.
STORE = os.path.expanduser("~/Library/Application Support/com.apple.wallpaper/Store/Index.plist")
RICE_WP_DIR = os.path.expanduser("~/.local/state/rice/wallpapers")

def _commit(p, verify):
    """Write the store and make WallpaperAgent pick it up. Order matters: write first,
    then SIGKILL the agent (SIGTERM lets it flush its stale in-memory copy over ours,
    and launchd relaunches it within milliseconds, so stop-edit-start races). The
    relaunched agent reads the file. verify(p2) re-reads the result; one retry."""
    for attempt in range(2):
        tmp = STORE + ".rice-tmp"
        with open(tmp, "wb") as fh:
            plistlib.dump(p, fh, fmt=plistlib.FMT_BINARY)
        os.replace(tmp, STORE)
        subprocess.run(["killall", "-9", "WallpaperAgent"], capture_output=True)
        for _ in range(50):
            if subprocess.run(["pgrep", "-x", "WallpaperAgent"], capture_output=True).returncode != 0:
                break
            time.sleep(0.1)
        subprocess.run(["launchctl", "kickstart", f"gui/{os.getuid()}/com.apple.wallpaper.agent"], capture_output=True)
        time.sleep(1.5)
        if verify(plistlib.load(open(STORE, "rb"))):
            return True
    print("wallpaper store: WallpaperAgent overwrote the store; wallpapers may be stale", file=sys.stderr)
    return False

def _desktop(png, fill_hex):
    """A Desktop block showing one image file, cropped to fill, letterbox in fill_hex."""
    now = datetime.datetime.now(datetime.timezone.utc).replace(tzinfo=None)
    rgb = [c / 255 for c in hex2rgb(fill_hex)] + [1.0]
    opts = {"values": {"color": {"color": {"_0": {"color": {"components": rgb,
            "colorSpace": plistlib.dumps("kCGColorSpaceGenericRGB", fmt=plistlib.FMT_BINARY)}}}},
            "placement": {"picker": {"_0": {"id": "Crop"}}}}}
    choice = {"Configuration": plistlib.dumps({"type": "imageFile", "url": {"relative": "file://" + png}}, fmt=plistlib.FMT_BINARY),
              "Files": [], "Provider": "com.apple.wallpaper.choice.image"}
    return {"Content": {"Choices": [choice], "EncodedOptionValues": plistlib.dumps(opts, fmt=plistlib.FMT_BINARY), "Shuffle": "$null"},
            "LastSet": now, "LastUse": now}

def _entry(old, png, fill_hex, idle_src):
    """Replace the Desktop of an entry, keeping its Idle (screen saver). A missing or
    'linked' entry becomes a fresh individual one with the system default screen saver."""
    e = copy.deepcopy(old) if isinstance(old, dict) and old.get("Type") == "individual" else {"Type": "individual"}
    e.setdefault("Idle", copy.deepcopy(idle_src))
    e["Desktop"] = _desktop(png, fill_hex)
    return e

def _entry_png(e):
    """Path of the image file an entry shows, or None (aerials, colours, linked, ...)."""
    try:
        url = plistlib.loads(e["Desktop"]["Content"]["Choices"][0]["Configuration"])["url"]["relative"]
        return url[len("file://"):] if url.startswith("file://") else None
    except Exception:  # noqa: BLE001
        return None

def _is_rice(e):
    p = _entry_png(e)
    return bool(p) and p.startswith(RICE_WP_DIR + "/")

def wallpaper_store_set(state, fill_hex, plan):
    """plan: [(space_uuid, display_uuid, png)] in Space order. The first png seen for
    a display also becomes that display's default (so new Spaces get it), and the very
    first one the system default. The untouched store is backed up once, before the
    first write, next to the snapshot."""
    backup = os.path.join(state, "wallpaper-store.pre-rice.plist")
    if not os.path.exists(backup):
        shutil.copy2(STORE, backup)
    p = plistlib.load(open(STORE, "rb"))
    idle = p.get("SystemDefault", {}).get("Idle", {})
    spaces, displays, seen = p.setdefault("Spaces", {}), p.setdefault("Displays", {}), set()
    for i, (suuid, duuid, png) in enumerate(plan):
        sp = spaces.setdefault(suuid, {})
        sp["Default"] = _entry(sp.get("Default"), png, fill_hex, idle)
        sp.setdefault("Displays", {})[duuid] = _entry(sp["Displays"].get(duuid), png, fill_hex, idle)
        if duuid not in seen:
            seen.add(duuid)
            displays[duuid] = _entry(displays.get(duuid), png, fill_hex, idle)
        if i == 0:
            p["SystemDefault"] = _entry(p.get("SystemDefault"), png, fill_hex, idle)
    def verify(p2):
        return all(_entry_png(p2.get("Spaces", {}).get(s, {}).get("Displays", {}).get(d, {})) == png for s, d, png in plan)
    _commit(p, verify)
    print(f"wallpaper store: {len(plan)} spaces on {len(seen)} displays")

def wallpaper_store_restore():
    """Undo: every entry that points into our wallpapers dir is replaced by the most
    recently set NON-rice entry for the same display (the user's previous wallpaper
    survives in Spaces that were never on screen while the rice ran), else by the
    newest non-rice entry anywhere. Returns how many entries could not be healed."""
    p = plistlib.load(open(STORE, "rb"))
    def when(e):
        try: return e["Desktop"]["LastSet"]
        except Exception: return datetime.datetime.min  # noqa: BLE001
    cands = {}                                                # display uuid | None -> (LastSet, entry)
    def consider(e, duuid):
        if not (isinstance(e, dict) and e.get("Type") == "individual" and "Desktop" in e) or _is_rice(e):
            return
        for key in (duuid, None):
            if key not in cands or when(e) > cands[key][0]:
                cands[key] = (when(e), e)
    for duuid, e in p.get("Displays", {}).items(): consider(e, duuid)
    for sp in p.get("Spaces", {}).values():
        consider(sp.get("Default"), None)
        for duuid, e in sp.get("Displays", {}).items(): consider(e, duuid)
    consider(p.get("SystemDefault"), None)
    left = 0
    def heal(e, duuid):
        nonlocal left
        if not _is_rice(e): return e
        c = cands.get(duuid) or cands.get(None)
        if c is None: left += 1; return e
        return copy.deepcopy(c[1])
    for duuid in list(p.get("Displays", {})): p["Displays"][duuid] = heal(p["Displays"][duuid], duuid)
    for sp in p.get("Spaces", {}).values():
        if "Default" in sp: sp["Default"] = heal(sp["Default"], None)
        for duuid in list(sp.get("Displays", {})): sp["Displays"][duuid] = heal(sp["Displays"][duuid], duuid)
    if "SystemDefault" in p: p["SystemDefault"] = heal(p["SystemDefault"], None)
    def verify(p2):
        return not any(_is_rice(e) for sp in p2.get("Spaces", {}).values() for e in sp.get("Displays", {}).values()) if left == 0 else True
    _commit(p, verify)
    print(f"wallpaper store: rice entries replaced, {left} left")
    return left

# ----------------------------------------------------------------------------- main
if __name__ == "__main__":
    a = sys.argv[1:]
    if not a:
        sys.exit(__doc__)
    cmd = a[0]
    if cmd == "palette" and len(a) == 4:
        write_palette(build_palette(a[1], a[2]), a[3])
    elif cmd == "render" and len(a) == 4:
        render(a[1], a[2], a[3])
    elif cmd == "accent" and len(a) == 2:
        accent(a[1])
    elif cmd == "snapshot-take" and len(a) == 2:
        snapshot_take(a[1])
    elif cmd == "snapshot-restore" and len(a) == 2:
        snapshot_restore(a[1])
    elif cmd == "wallpaper-store" and len(a) == 3:
        plan = [tuple(ln.split()[-3:]) for ln in sys.stdin if len(ln.split()) >= 3]
        wallpaper_store_set(a[1], a[2], plan)
    elif cmd == "wallpaper-store-restore" and len(a) == 1:
        wallpaper_store_restore()
    else:
        sys.exit(__doc__)
